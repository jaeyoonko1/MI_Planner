"""Write a FAKE process-plan workbook for developing/testing the P5-01 import (AGENTS.md: fake data only).

Usage:  python scripts/make_sample_plan_xlsx.py [--out PATH] [--variant 1|2]
Variant 1 is the first file. Variant 2 simulates the next revision of the same file (one step renamed,
one removed, one added) so re-import behaviour can be tried by hand.
The layout is deliberately untidy like real plan sheets: a title block above the header, blank product /
plan cells under the first row of a group, an extra column the app does not know, and extra sheets.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from app import xlsx  # noqa: E402

HEADER = ["제품", "Plan", "Step ID", "Step 이름", "공정 영역", "설비 그룹", "레시피", "레이어", "비고", "공정시간(분)"]


def _plan_a(variant: int) -> list[list]:
    rows = [
        ["PROD-TEST-A", "PLAN-A1", "S0010", "Gate Oxide Insp", "FEOL", "EQ-A01 group", "RCP-TEST-001", "L1", "", 12],
        ["", "", "S0020", "Poly Dep Meas", "FEOL", "EQ-A02 group", "RCP-TEST-002", "L2", "두께 측정", 8.5],
        ["", "", "S0030", "Contact Insp", "MOL", "EQ-A01 group", "RCP-TEST-003", "L3", "", 15],
        ["", "PLAN-A2", "S0010", "Gate Oxide Insp", "FEOL", "EQ-A01 group", "RCP-TEST-001", "L1", "", 12],
        ["", "", "S0040", "Metal1 Overlay", "BEOL", "EQ-B01 group", "RCP-TEST-004", "M1", "OVL", 10],
    ]
    if variant == 2:
        rows[1][3] = "Poly Dep Meas (rev)"  # renamed -> update
        rows.pop(2)  # S0030 removed -> missing
        rows.append(["", "", "S0050", "Metal2 Overlay", "BEOL", "EQ-B01 group", "RCP-TEST-005", "M2", "", 11])
    return rows


def build_sample(variant: int = 1) -> bytes:
    plan = xlsx.Sheet("Process Plan")
    plan.add(["PROCESS PLAN (FAKE SAMPLE)"], xlsx.STYLE_TITLE)
    plan.add(["generated by scripts/make_sample_plan_xlsx.py"])
    plan.add(HEADER, xlsx.STYLE_HEADER)
    for row in _plan_a(variant):
        plan.add(row)
    second = xlsx.Sheet("PLAN-B")  # product from a column, plan name from the sheet name
    second.add(["Product", "Step No", "Step Description", "Module", "Tool Group", "Remark"], xlsx.STYLE_HEADER)
    second.add(["PROD-TEST-B", "100", "Resist Insp", "LITHO", "EQ-C01 group", ""])
    second.add(["PROD-TEST-B", "110", "Etch CD Meas", "ETCH", "EQ-C02 group", "CD"])
    notes = xlsx.Sheet("README")
    notes.add(["not a plan sheet (FAKE)"])
    return xlsx.build_workbook([plan, second, notes])


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="sample_process_plan.xlsx")
    parser.add_argument("--variant", type=int, choices=(1, 2), default=1)
    args = parser.parse_args()
    Path(args.out).write_bytes(build_sample(args.variant))
    print(f"wrote {args.out} (variant {args.variant})")


if __name__ == "__main__":
    main()
